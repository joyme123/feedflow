/**
 * 前端将群聊纯文本转为 HTML：emoji + 链接
 */
export function buildChatHtml(text: string): string {
  if (!text) return ''

  // 先转义 HTML 特殊字符
  let html = text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')

  // 转换微博表情
  for (const [code, emoji] of Object.entries(CHAT_EMOJI_MAP)) {
    html = html.split(code).join(emoji)
  }

  // 转换 URL 为可点击链接
  html = html.replace(
    /(^|[^">])(https?:\/\/[^\s<>"']+)/g,
    '$1<a href="$2" target="_blank" rel="noopener noreferrer" onclick="event.preventDefault();window.open(this.href,\'_blank\')">$2</a>'
  )

  // 换行
  html = html.replace(/\n/g, '<br>')

  return html
}
